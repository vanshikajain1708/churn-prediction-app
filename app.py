import streamlit as st
import pandas as pd
import joblib

st.set_page_config(page_title="Customer Churn Predictor", page_icon="📉", layout="centered")

# ---------------- LOGIN SECTION ----------------
APP_PASSWORD = "churn2026"   # <-- change this to whatever password you want

if "logged_in" not in st.session_state:
    st.session_state.logged_in = False

if not st.session_state.logged_in:
    st.title("🔒 Login")
    st.write("Please enter the password to access the Customer Churn Prevention System.")
    password_input = st.text_input("Password", type="password")

    if st.button("Login"):
        if password_input == APP_PASSWORD:
            st.session_state.logged_in = True
            st.rerun()
        else:
            st.error("Incorrect password. Please try again.")

    st.stop()   # stops the app here until logged in
# -------------------------------------------------

st.title("📉 Customer Churn Prevention System")
st.write("Enter customer details to predict churn risk and see the key drivers.")

# --- Load trained artifacts (must be in the same folder, generated by the notebook) ---
model = joblib.load("churn_model.pkl")
scaler = joblib.load("churn_scaler.pkl")
model_columns = joblib.load("churn_columns.pkl")

# --- User Inputs ---
col1, col2 = st.columns(2)

with col1:
    gender = st.selectbox("Gender", ["Male", "Female"])
    senior = st.selectbox("Senior Citizen", ["No", "Yes"])
    partner = st.selectbox("Has Partner", ["Yes", "No"])
    dependents = st.selectbox("Has Dependents", ["Yes", "No"])
    tenure = st.slider("Tenure (months)", 0, 72, 12)
    phone_service = st.selectbox("Phone Service", ["Yes", "No"])
    multiple_lines = st.selectbox("Multiple Lines", ["No", "Yes", "No phone service"])
    internet_service = st.selectbox("Internet Service", ["DSL", "Fiber optic", "No"])
    online_security = st.selectbox("Online Security", ["No", "Yes", "No internet service"])
    online_backup = st.selectbox("Online Backup", ["No", "Yes", "No internet service"])

with col2:
    device_protection = st.selectbox("Device Protection", ["No", "Yes", "No internet service"])
    tech_support = st.selectbox("Tech Support", ["No", "Yes", "No internet service"])
    streaming_tv = st.selectbox("Streaming TV", ["No", "Yes", "No internet service"])
    streaming_movies = st.selectbox("Streaming Movies", ["No", "Yes", "No internet service"])
    contract = st.selectbox("Contract", ["Month-to-month", "One year", "Two year"])
    paperless = st.selectbox("Paperless Billing", ["Yes", "No"])
    payment_method = st.selectbox("Payment Method", [
        "Electronic check", "Mailed check",
        "Bank transfer (automatic)", "Credit card (automatic)"
    ])
    monthly_charges = st.number_input("Monthly Charges ($)", 0.0, 200.0, 70.0)
    total_charges = st.number_input("Total Charges ($)", 0.0, 10000.0, 840.0)

# --- Build raw input dict matching original dataset columns ---
raw_input = {
    "gender": gender, "SeniorCitizen": 1 if senior == "Yes" else 0,
    "Partner": partner, "Dependents": dependents, "tenure": tenure,
    "PhoneService": phone_service, "MultipleLines": multiple_lines,
    "InternetService": internet_service, "OnlineSecurity": online_security,
    "OnlineBackup": online_backup, "DeviceProtection": device_protection,
    "TechSupport": tech_support, "StreamingTV": streaming_tv,
    "StreamingMovies": streaming_movies, "Contract": contract,
    "PaperlessBilling": paperless, "PaymentMethod": payment_method,
    "MonthlyCharges": monthly_charges, "TotalCharges": total_charges
}

input_df = pd.DataFrame([raw_input])

# One-hot encode same way as training, then align columns
input_encoded = pd.get_dummies(input_df)
input_encoded = input_encoded.reindex(columns=model_columns, fill_value=0)

# Scale numeric columns
num_cols = ["tenure", "MonthlyCharges", "TotalCharges"]
input_encoded[num_cols] = scaler.transform(input_encoded[num_cols])

if st.button("Predict Churn Risk"):
    proba = model.predict_proba(input_encoded)[0][1]
    prediction = model.predict(input_encoded)[0]

    st.subheader("Result")
    if prediction == 1:
        st.error(f"⚠️ High Churn Risk — Probability: {proba:.1%}")
    else:
        st.success(f"✅ Low Churn Risk — Probability: {proba:.1%}")

    st.progress(min(int(proba * 100), 100))

    # Top 5 global feature importances as a quick "why" explanation
    st.subheader("Top Factors Influencing Churn (Model-wide)")
    importances = pd.Series(model.feature_importances_, index=model_columns)
    top5 = importances.sort_values(ascending=False).head(5)
    st.bar_chart(top5)

st.caption("Model: Random Forest Classifier | Trained on IBM Telco Customer Churn dataset")
